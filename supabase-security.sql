create table if not exists public.vote_ballots (
  id bigint generated by default as identity primary key,
  election_id bigint not null references public.elections(id) on delete cascade,
  voter_id uuid not null references auth.users(id) on delete cascade,
  selections jsonb not null,
  created_at timestamptz not null default now(),
  unique (election_id, voter_id)
);

alter table public.elections add column if not exists start_date date;
alter table public.elections add column if not exists end_date date;
alter table public.elections add column if not exists deadline time;
alter table public.elections add column if not exists eligible_voters integer default 0;
alter table public.candidates add column if not exists initials text;
alter table public.candidates add column if not exists description text;

update public.elections
set start_date = coalesce(start_date, current_date),
    end_date = coalesce(end_date, current_date + 7),
    deadline = coalesce(deadline, '23:59'::time),
    eligible_voters = coalesce(eligible_voters, 100)
where id = 1;

alter table public.vote_ballots enable row level security;
alter table public.elections enable row level security;
alter table public.candidates enable row level security;

grant select, insert, update, delete on public.elections, public.candidates to authenticated;
grant insert on public.vote_ballots to authenticated;
grant select on public.vote_ballots to authenticated;

