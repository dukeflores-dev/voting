-- Run this once in Supabase SQL Editor.
-- This table stores one complete ballot per authenticated voter.
create table if not exists public.elections (
  id bigint generated by default as identity primary key,
  title text not null,
  status text not null default 'active' check (status in ('active', 'closed')),
  start_date date not null default current_date,
  end_date date not null default (current_date + 7),
  deadline time not null default '23:59',
  eligible_voters integer not null default 100,
  created_at timestamptz not null default now()
);

create table if not exists public.candidates (
  id bigint generated by default as identity primary key,
  election_id bigint not null references public.elections(id) on delete cascade,
  name text not null,
  position text not null,
  initials text not null,
  description text,
  image_url text,
  created_at timestamptz not null default now()
);

